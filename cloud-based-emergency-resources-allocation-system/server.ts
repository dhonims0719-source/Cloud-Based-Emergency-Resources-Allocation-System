import express from "express";
import path from "path";
import { fileURLToPath } from "url";
import { createServer as createViteServer } from "vite";
import { GoogleGenAI } from "@google/genai";
import dotenv from "dotenv";

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

async function startServer() {
  const app = express();
  const PORT = 3000;

  app.use(express.json({ limit: "15mb" }));

  // Health check endpoint
  app.get("/api/health", (_req, res) => {
    res.json({
      status: "ok",
      system: "Cloud-Based Emergency Resources Allocation System",
      timestamp: new Date().toISOString(),
      hasGeminiKey: Boolean(process.env.GEMINI_API_KEY),
    });
  });

  // AI Assistant endpoint using Gemini 2.5 Flash
  app.post("/api/ai-assistant", async (req, res) => {
    try {
      const { prompt, incidentContext, mode } = req.body;
      const apiKey = process.env.GEMINI_API_KEY;

      if (!prompt) {
        return res.status(400).json({ error: "Missing prompt parameter." });
      }

      if (apiKey) {
        const ai = new GoogleGenAI({ apiKey });
        const systemInstruction = `You are an elite Emergency Operations Center (EOC) AI Decision-Support Specialist for the Cloud-Based Emergency Resources Allocation System.
Your job is to provide clear, actionable, structured triage analysis, resource recommendations, hospital routing advice, and risk assessments.
Always format your answers cleanly with:
1. Executive Assessment (Severity Score 1-10, Primary Hazard)
2. Recommended Resource Package (Rescue teams, Ambulances, Fire units, Medical supplies)
3. Hospital & Shelter Routing Strategy
4. Key Operational Hazards & Mitigation
5. Formal Disclaimer: Always remind the human incident commander that this is decision-support guidance requiring human approval before dispatch.
Keep language professional, urgent, precise, and structured with bullet points.`;

        const response = await ai.models.generateContent({
          model: "gemini-2.5-flash",
          contents: [
            {
              role: "user",
              parts: [
                {
                  text: `System Context: Mode=${mode || "general-support"}\nIncident Data: ${
                    incidentContext ? JSON.stringify(incidentContext) : "No active incident selected."
                  }\n\nOfficer Query: ${prompt}`,
                },
              ],
            },
          ],
          config: {
            systemInstruction,
            temperature: 0.3,
          },
        });

        const text = response.text || "No response generated by AI model.";
        return res.json({ response: text, source: "gemini-2.5-flash" });
      }

      // If GEMINI_API_KEY is not set, provide an intelligent high-precision heuristic tactical response
      const fallbackResponse = generateHeuristicResponse(prompt, incidentContext);
      return res.json({
        response: fallbackResponse,
        source: "tactical-heuristic-engine",
        notice: "Running on Tactical Heuristic Decision Engine (Add GEMINI_API_KEY in settings to enable live Gemini Flash analysis).",
      });
    } catch (err: any) {
      console.error("AI Assistant error:", err);
      return res.status(500).json({
        error: err?.message || "Failed to generate AI decision support analysis.",
      });
    }
  });

  // Vite middleware for development vs static serving in production
  if (process.env.NODE_ENV !== "production") {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: "spa",
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.join(process.cwd(), "dist");
    app.use(express.static(distPath));
    app.get("*", (_req, res) => {
      res.sendFile(path.join(distPath, "index.html"));
    });
  }

  app.listen(PORT, "0.0.0.0", () => {
    console.log(`Emergency Operations Server running on http://0.0.0.0:${PORT}`);
  });
}

function generateHeuristicResponse(prompt: string, context: any): string {
  const p = prompt.toLowerCase();
  const title = context?.title || "Active Emergency Incident";
  const type = context?.type || "Multi-Agency Incident";
  const priority = context?.priority || "High";
  const casualties = context?.affectedPeople || 8;
  const location = context?.location || "Metro Sector 4";

  if (p.includes("shortage") || p.includes("resource crunch")) {
    return `### ⚠️ Tactical Resource & Surge Advisory

**1. Current Deficit Analysis:**
- **ICU Bed Pressure:** Metro Central Hospital is at 88% capacity. Recommend routing non-critical cases to Highland Medical.
- **Paramedic ALS Units:** 2 of 6 ambulances deployed. Surge capacity buffer stands at 66%.
- **Swiftwater/Hazmat Teams:** Regional Swiftwater Team Alpha is on standby at Station 3.

**2. Recommended Mitigation Measures:**
- Pre-stage 10 additional portable oxygen cylinders at Sector 4 staging depot.
- Request mutual aid standby from Sector 5 Fire Station for ladder operations.
- Issue shelter alert for Riverside Community Center (currently 42% capacity).

*Notice: This recommendation is generated for tactical decision-support. Incident Commander approval required.*`;
  }

  if (p.includes("hospital") || p.includes("bed") || p.includes("casualty")) {
    return `### 🏥 Hospital Triage & Bed Allocation Matrix

**Target Incident:** ${title} (${location})
**Estimated Casualties:** ${casualties} persons requiring triage

**Recommended Routing:**
1. **Memorial Trauma Center (Level 1)** — 4.2 km away (ETA 7 mins)
   - *Allocation:* 3 Critical ICU candidates, Red Tag triage
   - *Status:* 14 ICU beds, 42 General beds available
2. **City General Hospital** — 6.8 km away (ETA 12 mins)
   - *Allocation:* 5 Yellow/Green non-critical injuries
   - *Status:* 28 General beds available, Burn unit on standby

**Ambulance Dispatch Recommendation:**
- Dispatch 2 Advanced Life Support (ALS) units and 1 Mass Casualty transport vehicle immediately.

*Disclaimer: AI decision-support recommendation. Confirm bed availability with EOC dispatch officer.*`;
  }

  return `### 🚨 Tactical Decision-Support Assessment: ${title}

**1. Incident Severity & Hazard Classification:**
- **Triage Level:** ${priority.toUpperCase()} Priority (${type})
- **Location:** ${location}
- **Affected Population:** Approximately ${casualties} individuals identified
- **Primary Hazards:** Structural entrapment risk, localized congestion, emergency vehicle access choke points.

**2. Recommended Resource Dispatch Package:**
- **Rescue Units:** 1 Urban Search & Rescue (USAR) Specialist Team (Team Alpha-1)
- **Medical Fleet:** 2 ALS Ambulances (AMB-102, AMB-104)
- **Fire & Suppression:** 1 Rapid Response Engine (ENG-04)
- **Equipment Pod:** 20 Standard Trauma Kits, 4 Portable O2 Units, 1 Heavy Extraction Kit

**3. Evacuation & Shelter Coordination:**
- Direct uninjured displaced residents to **Civic Arena Shelter** (550 beds available).
- Establish a 300-meter safety perimeter; request Police traffic diversion at North & 5th Avenue.

**4. Incident Commander Action Items:**
- [ ] Verify perimeter security with Field Commander.
- [ ] Approve recommended resource allocation in the Dispatch Module.
- [ ] Issue localized citizen notification broadcast.

*Disclaimer: AI generated decision-support intelligence. Requires human validation before field execution.*`;
}

startServer();
